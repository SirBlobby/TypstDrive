use axum::{
    extract::DefaultBodyLimit,
    routing::{delete, get, patch, post, put},
    Router,
};
use tower_http::services::{ServeDir, ServeFile};
use tower_http::trace::TraceLayer;

use crate::{
    accounts, admin, api, compile, desktop, drive, packages, realtime, request_context, security_headers, sharing, teams, AppState,
};

pub fn build_router(state: AppState) -> Router {
    let api_routes = Router::new()
        .route("/setup", get(accounts::setup::setup_status).post(accounts::setup::run_setup))
        .route("/admin/users", get(admin::users::list_users).post(admin::users::create_user))
        .route("/admin/users/{id}", patch(admin::users::update_user).delete(admin::users::delete_user))
        .route("/admin/users/{id}/sessions", delete(admin::users::revoke_user_sessions))
        .route("/admin/users/{id}/password", put(admin::user_password::set_user_password))
        .route("/admin/authentication", get(admin::authentication::get_authentication).put(admin::authentication::update_authentication))
        .route("/admin/branding", put(admin::branding::update_branding))
        .route(
            "/admin/branding/logo",
            put(admin::branding::upload_logo)
                .delete(admin::branding::remove_logo)
                .layer(DefaultBodyLimit::max(accounts::avatars::MAX_UPLOAD_BYTES)),
        )
        .route("/branding", get(admin::branding::public_branding))
        .route("/branding/logo", get(admin::branding::get_logo))
        .route("/admin/email/test", post(admin::authentication::send_test_email))
        .route("/admin/audit-log", get(admin::audit::list_entries))
        .route("/admin/teams", get(teams::admin::list_all_teams))
        .route("/admin/teams/{id}", delete(teams::admin::delete_any_team))
        .route("/admin/team-policy", get(teams::policy::get_policy).put(teams::policy::update_policy))
        .route("/admin/account-policy", get(accounts::policy::get_policy).put(accounts::policy::update_policy))
        .route("/admin/api-access", get(api::limits::overview))
        .route("/admin/api-access/defaults", put(api::limits::update_defaults))
        .route("/admin/api-access/users/{id}", put(api::limits::update_user_limits))
        .route("/admin/pdf-links", get(sharing::pdf_links::admin::overview))
        .route("/admin/pdf-links/policy", get(sharing::pdf_links::policy::get_policy).put(sharing::pdf_links::policy::update_policy))
        .route("/admin/pdf-links/{id}", delete(sharing::pdf_links::admin::delete_link))
        .route("/admin/package-policy", get(packages::policy::get_policy).put(packages::policy::update_policy))
        .route("/admin/server", get(admin::server_info::server_info))
        .route("/admin/storage", get(accounts::storage::overview))
        .route("/admin/storage/default-quota", put(accounts::storage::update_default_quota))
        .route("/admin/storage/users/{id}", put(accounts::storage::update_user_quota))
        .route(
            "/admin/storage/version-history",
            get(drive::versions::retention::get_version_limit).put(drive::versions::retention::update_version_limit),
        )
        .route("/compile", post(compile::handlers::compile_handler))
        .route("/export/{format}", post(compile::handlers::export_handler))
        .route("/export/pandoc/{format}", post(compile::pandoc::pandoc_export_handler))
        .route("/import/pandoc", post(compile::pandoc::pandoc_import_handler))
        .route("/lsp/{id}", get(compile::lsp::lsp_handler))
        .route("/auth/register", post(accounts::auth::register))
        .route("/auth/login", post(accounts::auth::login))
        .route("/auth/logout", post(accounts::auth::logout))
        .route("/auth/me", get(accounts::auth::me).put(accounts::auth::update_profile))
        .route(
            "/auth/avatar",
            get(accounts::avatars::get_avatar)
                .put(accounts::avatars::upload_avatar)
                .delete(accounts::avatars::delete_avatar)
                .layer(DefaultBodyLimit::max(accounts::avatars::MAX_UPLOAD_BYTES)),
        )
        .route("/auth/storage", get(accounts::storage::own_storage))
        .route("/users/{id}/avatar", get(accounts::avatars::get_user_avatar))
        .route("/auth/policy", get(accounts::policy::public_policy))
        .route("/auth/change-password", put(accounts::auth::change_password))
        .route("/auth/options", get(accounts::auth_settings::auth_options))
        .route("/auth/sessions", get(accounts::sessions::list_sessions))
        .route("/auth/sessions/revoke-others", post(accounts::sessions::revoke_other_sessions))
        .route("/auth/sessions/{id}", delete(accounts::sessions::revoke_session))
        .route("/auth/verify-email", post(accounts::verification::verify_email))
        .route("/auth/verify-email/code", post(accounts::verification::verify_with_code))
        .route("/auth/verify-email/resend", post(accounts::verification::resend_verification))
        .route("/auth/email-code/request", post(accounts::email_code::request_code))
        .route("/auth/email-code/sign-in", post(accounts::email_code::sign_in_with_code))
        .route("/auth/password-reset/request", post(accounts::password_reset::request_reset))
        .route("/auth/password-reset/confirm", post(accounts::password_reset::confirm_reset))
        .route("/auth/sso/{provider}/start", get(accounts::sso::handlers::start))
        .route("/auth/sso/{provider}/callback", get(accounts::sso::handlers::callback))
        .route("/auth/identities", get(accounts::sso::list_identities))
        .route("/auth/identities/{id}", delete(accounts::sso::unlink_identity))
        .route("/teams", get(teams::handlers::list_teams).post(teams::handlers::create_team))
        .route("/teams/policy", get(teams::policy::own_policy))
        .route("/teams/{id}", get(teams::handlers::get_team).patch(teams::handlers::rename_team).delete(teams::handlers::delete_team))
        .route("/teams/{id}/members", post(teams::members::add_member))
        .route("/teams/{id}/members/{user_id}", patch(teams::members::change_member_role).delete(teams::members::remove_member))
        .route("/teams/{id}/members/{user_id}/transfer", post(teams::members::transfer_ownership))
        .route("/share-links/{kind}/{id}", get(sharing::links::link_status).put(sharing::links::update_link))
        .route("/share-links/{kind}/{id}/unlock", post(sharing::links::unlock_link))
        .route("/pdf-links", get(sharing::pdf_links::manage::list_own_links))
        .route(
            "/pdf-links/{kind}/{id}",
            get(sharing::pdf_links::manage::get_item_link)
                .put(sharing::pdf_links::manage::save_item_link)
                .delete(sharing::pdf_links::manage::delete_item_link),
        )
        .route("/item-info/{kind}/{id}", get(drive::item_info::get_item_info))
        .route("/stars", get(drive::stars::list_starred))
        .route("/stars/{kind}/{id}", put(drive::stars::star_item).delete(drive::stars::unstar_item))
        .route("/folders", get(drive::folders::list_folders).post(drive::folders::create_folder))
        .route("/folders/shared", get(drive::folders::list_shared_folders))
        .route("/transfers", get(sharing::ownership::list_transfers).post(sharing::ownership::request_transfer))
        .route("/transfers/{id}", delete(sharing::ownership::cancel_transfer))
        .route("/transfers/{id}/accept", post(sharing::ownership::accept_transfer))
        .route("/share-info/{kind}/{id}", get(sharing::ownership::share_info))
        .route("/folders/{id}/collaborators", get(sharing::members::list_folder_collaborators))
        .route("/folders/{id}/collaborators/{collab_id}", delete(sharing::members::remove_folder_collaborator))
        .route("/folders/{id}/invite", post(sharing::members::invite_folder_collaborator))
        .route("/folders/{id}", delete(drive::folders::delete_folder).patch(drive::folders::update_folder))
        .route("/folders/{id}/color", patch(drive::folder_colors::set_folder_color))
        .route("/folders/{id}/download", get(drive::downloads::download_folder))
        .route("/fonts", get(drive::files::list_fonts))
        .route("/files", get(drive::files::list_files).post(drive::files::upload_file_global))
        .route("/files/{id}", delete(drive::files::delete_file).patch(drive::files::update_file))
        .route("/files/{id}/data", get(drive::files::get_file_data).put(drive::file_replace::replace_file_data))
        .route("/docs/shared", get(drive::documents::list_shared_documents))
        .route("/docs/search", get(drive::content_search::search_document_text))
        .route("/docs", get(drive::documents::list_documents).post(drive::documents::create_document))
        .route("/docs/{id}", get(drive::documents::get_document).delete(drive::documents::delete_document).patch(drive::documents::update_document))
        .route("/docs/{id}/files", get(drive::document_assets::list_assets).post(drive::document_assets::upload_asset))
        .route("/docs/{id}/files/{file_id}", get(drive::document_assets::get_asset_data))
        .route("/docs/{id}/files/share-unshared", post(drive::document_assets::attach_unshared_assets))
        .route("/docs/{id}/files/{file_id}/attach", post(drive::document_assets::attach_asset))
        .route("/docs/{id}/fonts", get(drive::document_assets::list_fonts))
        .route("/docs/{id}/library/images", get(drive::editor_library::list_images))
        .route("/docs/{id}/text", get(drive::editor_library::document_text))
        .route("/editor/documents", get(drive::editor_library::list_documents))
        .route("/docs/{id}/collaborators", get(sharing::members::list_document_collaborators))
        .route("/docs/{id}/collaborators/{collab_id}", delete(sharing::members::remove_document_collaborator))
        .route("/docs/{id}/invite", post(sharing::members::invite_document_collaborator))
        .route("/docs/{id}/comments", get(drive::comments::get_comments).post(drive::comments::add_comment))
        .route("/docs/{id}/versions", get(drive::versions::get_versions).post(drive::versions::create_version))
        .route("/docs/{id}/versions/{version_id}", patch(drive::versions::rename_version))
        .route("/docs/{id}/versions/{version_id}/restore", post(drive::versions::restore_version))
        .route("/comments/{id}", patch(drive::comments::update_comment).delete(drive::comments::delete_comment))
        .route("/docs/{id}/suggestions", get(drive::suggestions::list_suggestions).post(drive::suggestions::create_suggestion))
        .route("/suggestions/{id}", patch(drive::suggestions::update_suggestion))
        .route("/keys", get(api::keys::list_keys).post(api::keys::create_key))
        .route("/keys/usage", get(api::keys::get_aggregate_usage))
        .route("/keys/limits", get(api::limits::own_limits))
        .route("/keys/{id}", delete(api::keys::delete_key))
        .route("/keys/{id}/regenerate", post(api::keys::regenerate_key))
        .route("/projects/shared", get(drive::projects::list_shared_projects))
        .route("/projects", get(drive::projects::list_projects).post(drive::projects::create_project))
        .route("/projects/{id}", get(drive::projects::get_project).delete(drive::projects::delete_project).patch(drive::projects::update_project))
        .route("/projects/{id}/download", get(drive::downloads::download_project))
        .route("/projects/{id}/collaborators", get(sharing::members::list_project_collaborators))
        .route("/projects/{id}/collaborators/{collab_id}", delete(sharing::members::remove_project_collaborator))
        .route("/projects/{id}/invite", post(sharing::members::invite_project_collaborator))
        .route("/projects/{id}/files", get(drive::projects::list_project_files).post(drive::projects::create_project_file))
        .route("/projects/{id}/files/upload", post(drive::projects::upload_project_file))
        .route("/projects/{id}/entrypoint", put(drive::project_entrypoints::set_project_entrypoint))
        .route("/projects/{id}/folders", patch(drive::project_folders::rename_project_folder).delete(drive::project_folders::delete_project_folder))
        .route("/projects/{id}/files/{fid}", get(drive::projects::get_project_file).patch(drive::projects::update_project_file).delete(drive::projects::delete_project_file))
        .route("/packages", get(packages::registry::list_packages))
        .route("/packages/publish", post(packages::registry::publish_package))
        .route("/packages/policy", get(packages::policy::own_policy))
        .route("/packages/{name}", get(packages::registry::list_versions).delete(packages::registry::delete_package))
        .route("/packages/{name}/access", get(packages::sharing::get_access))
        .route("/packages/{name}/access/visibility", put(packages::sharing::update_visibility))
        .route("/packages/{name}/access/users", post(packages::sharing::add_user))
        .route("/packages/{name}/access/users/{user_id}", delete(packages::sharing::remove_user))
        .route("/packages/{name}/access/teams", post(packages::sharing::add_team))
        .route("/packages/{name}/access/teams/{team_id}", delete(packages::sharing::remove_team))
        .route("/desktop-link-codes", post(desktop::link_codes::create_link_code))
        .route("/devices", get(desktop::devices::list_devices))
        .route("/devices/{id}", delete(desktop::devices::revoke_device));

    let desktop_routes = Router::new()
        .route("/version", get(desktop::version_info))
        .route("/auth/login", post(desktop::session::login))
        .route("/auth/logout", post(desktop::session::logout))
        .route("/auth/exchange", post(desktop::link_codes::exchange_link_code))
        .route("/auth/me", get(desktop::session::me))
        .route("/projects", get(desktop::projects::list_projects).post(desktop::projects::create_project))
        .route("/projects/{id}", get(desktop::project_files::pull_project).delete(desktop::projects::delete_project).patch(desktop::projects::move_project))
        .route("/projects/{id}/manifest", get(desktop::project_files::get_manifest))
        .route("/folders", get(desktop::folders::list_folders).post(desktop::folders::create_folder))
        .route("/folders/{id}", patch(desktop::folders::rename_folder).delete(desktop::folders::delete_folder))
        .route("/folders/{id}/move", patch(desktop::folders::move_folder))
        .route("/folders/{id}/color", patch(desktop::folders::set_folder_color))
        .route("/documents", get(desktop::documents::list_documents).post(desktop::documents::create_document))
        .route("/documents/{id}", get(desktop::documents::pull_document).put(desktop::documents::push_document).delete(desktop::documents::delete_document).patch(desktop::documents::move_document))
        .route("/shared", get(desktop::documents::list_shared))
        .route("/spaces", get(desktop::spaces::list_spaces))
        .route("/files", get(desktop::files::list_account_files).post(desktop::files::upload_account_file))
        .route("/files/{id}", get(desktop::files::pull_account_file).patch(desktop::files::rename_account_file).delete(desktop::files::delete_account_file))
        .route("/files/{id}/move", patch(desktop::files::move_account_file))
        .route("/projects/{id}/file", get(desktop::project_files::pull_file).put(desktop::project_files::push_file).delete(desktop::project_files::delete_file))
        .route("/documents/{id}/versions", get(drive::versions::get_versions).post(drive::versions::create_version))
        .route("/documents/{id}/versions/{version_id}", patch(drive::versions::rename_version))
        .route("/documents/{id}/versions/{version_id}/restore", post(drive::versions::restore_version))
        .route("/documents/{id}/comments", get(drive::comments::get_comments).post(drive::comments::add_comment))
        .route("/comments/{id}", patch(drive::comments::update_comment).delete(drive::comments::delete_comment))
        .route("/documents/{id}/suggestions", get(drive::suggestions::list_suggestions).post(drive::suggestions::create_suggestion))
        .route("/suggestions/{id}", patch(drive::suggestions::update_suggestion))
        .route("/users/{id}/avatar", get(accounts::avatars::get_user_avatar))
        .route("/ws", get(desktop::devices::ws_handler));

    let v1_routes = Router::new()
        .route("/render", post(api::render::render_handler))
        .route("/documents", get(api::read::documents::list_documents))
        .route("/documents/{id}", get(api::read::documents::get_document))
        .route("/documents/{id}/render", post(api::stored_render::render_document))
        .route("/documents/{id}/versions", get(api::read::documents::get_document_versions))
        .route("/documents/{id}/versions/{version_id}", get(api::read::documents::get_document_version))
        .route("/documents/{id}/comments", get(api::read::documents::get_document_comments))
        .route("/documents/{id}/suggestions", get(api::read::documents::get_document_suggestions))
        .route("/projects", get(api::read::projects::list_projects))
        .route("/projects/{id}", get(api::read::projects::get_project))
        .route("/projects/{id}/render", post(api::stored_render::render_project))
        .route("/projects/{id}/files/{file_id}", get(api::read::projects::get_project_file))
        .route("/folders", get(api::read::folders::list_folders))
        .route("/files", get(api::read::files::list_files))
        .route("/files/{id}", get(api::read::files::get_file))
        .route("/starred", get(api::read::starred::list_starred))
        .route("/teams", get(api::read::teams::list_teams));

    let yjs_routes = Router::new()
        .route("/{id}", get(realtime::yjs::yjs_handler));

    let static_dir = std::env::var("STATIC_DIR").unwrap_or_else(|_| "../build".to_string());

    Router::new()
        .nest("/api", api_routes.nest("/desktop", desktop_routes).layer(TraceLayer::new_for_http()))
        .nest("/v1", v1_routes.layer(TraceLayer::new_for_http()))
        .nest("/yjs", yjs_routes.layer(TraceLayer::new_for_http()))
        .route("/pdf/{slug}", get(sharing::pdf_links::serve::serve_pdf).layer(TraceLayer::new_for_http()))
        .fallback_service(ServeDir::new(&static_dir).fallback(ServeFile::new(format!("{}/index.html", static_dir))))
        .layer(axum::middleware::from_fn_with_state(state.clone(), request_context::attach_request_context))
        .layer(axum::middleware::from_fn(security_headers::add_security_headers))
        .with_state(state)
}
